"""
Defensive Rules & Incident Mitigation Synthesizer.
Automatically generates SIGMA, Snort/Suricata, and Firewall ACL rules from intercepted adversary probes.
"""

import time
import os
from typing import Dict, Any, List

class RulesGenerator:
    @staticmethod
    def generate_sigma_rule(incident: Dict[str, Any]) -> str:
        """
        Synthesizes a production-grade SIGMA detection rule based on intercepted adversary behavior.
        """
        fingerprint = incident.get("fingerprint", {})
        mitre_list = incident.get("mitre_mappings", [])
        
        rule_title = f"PhantomMesh Alert - Observed {fingerprint.get('method', 'GET')} Recon on {fingerprint.get('path', '/')}"
        rule_id = f"phantom-{int(time.time())}-{os.getpid()}"
        
        mitre_tags = []
        for m in mitre_list:
            t_id = m.get("technique_id", "").lower()
            if t_id:
                mitre_tags.append(f"attack.{t_id}")
                
        tags_str = "\n".join([f"    - {t}" for t in mitre_tags]) if mitre_tags else "    - attack.reconnaissance"
        
        path_escaped = fingerprint.get("path", "/").replace('"', '\\"')
        ua_escaped = fingerprint.get("user_agent", "").replace('"', '\\"')
        
        sigma_yaml = f"""title: {rule_title}
id: {rule_id}
status: experimental
description: Auto-generated by PhantomMesh Cyber Deception Engine. Detects targeted adversary probing and exploitation attempts.
author: PhantomMesh Autonomous Defense
references:
    - https://github.com/phantom-mesh/deception-engine
tags:
{tags_str}
logsource:
    category: webserver
    service: http
detection:
    selection_path:
        cs-method: '{fingerprint.get("method", "GET")}'
        c-uri-stem|contains: '{path_escaped}'
    selection_ua:
        c-user-agent|contains: '{ua_escaped[:40]}'
    condition: selection_path or selection_ua
falsepositives:
    - Highly unlikely (Target URI is a dedicated deceptive canary asset)
level: {incident.get("risk", {}).get("level", "HIGH").lower()}
"""
        return sigma_yaml

    @staticmethod
    def generate_snort_rule(incident: Dict[str, Any], sid: int = 1009001) -> str:
        """
        Generates a Snort / Suricata IDS network signature.
        """
        fingerprint = incident.get("fingerprint", {})
        path = fingerprint.get("path", "/")[:50]
        # Clean path for snort content
        clean_content = path.split('?')[0].replace('"', '')
        
        snort_rule = (
            f'alert tcp any any -> $HOME_NET $HTTP_PORTS '
            f'(msg:"PHANTOM-MESH - Deception Asset Probed [{clean_content}]"; '
            f'flow:to_server,established; '
            f'content:"{clean_content}"; http_uri; '
            f'classtype:attempted-recon; '
            f'sid:{sid}; rev:1;)'
        )
        return snort_rule

    @staticmethod
    def generate_firewall_acl(client_ip: str) -> Dict[str, str]:
        """
        Generates platform-specific commands to immediately quarantine or block the attacker IP.
        """
        return {
            "windows": f'netsh advfirewall firewall add rule name="PhantomMesh-Block-{client_ip}" dir=in action=block remoteip={client_ip}',
            "linux_iptables": f'iptables -I INPUT -s {client_ip} -j DROP',
            "linux_nftables": f'nft add rule inet filter input ip saddr {client_ip} drop',
            "aws_nacl_suggestion": f'Deny Inbound Traffic from {client_ip}/32 on All Ports'
        }
